import streamlit as st
import pandas as pd
import plotly.express as px

# =====================================
# 1. KONFIGURASI DASHBOARD
# =====================================
st.set_page_config(
    page_title="Dashboard Data Fiskal",
    page_icon="📊",
    layout="wide"
)

# =====================================
# 2. MEMBACA DATASET DARI GITHUB
# =====================================
URL = (
    "https://raw.githubusercontent.com/"
    "Alam-A99/DATAAKSI/main/"
    "dataset_fiskal_97_hipoFull.csv"
)

@st.cache_data
def load_data():
    df = pd.read_csv(URL)

    # Membersihkan nama kolom
    df.columns = df.columns.str.strip()

    # Memastikan kolom tahun berbentuk angka
    if "Tahun" in df.columns:
        df["Tahun"] = pd.to_numeric(
            df["Tahun"], errors="coerce"
        )

    return df

try:
    df = load_data()
except Exception as e:
    st.error(f"Gagal membaca dataset: {e}")
    st.stop()

# =====================================
# 3. JUDUL DASHBOARD
# =====================================
st.title("📊 Dashboard Data Fiskal Daerah")
st.write(
    "Visualisasi data penerimaan fiskal, belanja pemerintah, "
    "dan indikator sosial ekonomi berdasarkan kota dan tahun."
)

st.divider()

# =====================================
# 4. FILTER DATA
# =====================================
st.sidebar.header("🔎 Filter Data")

if "Kota" in df.columns:
    daftar_kota = sorted(
        df["Kota"].dropna().unique().tolist()
    )
    pilihan_kota = st.sidebar.multiselect(
        "Pilih Kota",
        options=daftar_kota,
        default=daftar_kota
    )
else:
    pilihan_kota = []

if "Tahun" in df.columns:
    tahun_valid = df["Tahun"].dropna()

    if not tahun_valid.empty:
        tahun_min = int(tahun_valid.min())
        tahun_max = int(tahun_valid.max())

        rentang_tahun = st.sidebar.slider(
            "Rentang Tahun",
            min_value=tahun_min,
            max_value=tahun_max,
            value=(tahun_min, tahun_max)
        )
    else:
        rentang_tahun = None
else:
    rentang_tahun = None

# Menerapkan filter
data = df.copy()

if "Kota" in data.columns:
    data = data[data["Kota"].isin(pilihan_kota)]

if "Tahun" in data.columns and rentang_tahun:
    data = data[
        data["Tahun"].between(
            rentang_tahun[0],
            rentang_tahun[1]
        )
    ]

if data.empty:
    st.warning("Tidak ada data untuk filter yang dipilih.")
    st.stop()

# =====================================
# 5. RINGKASAN DATA
# =====================================
kolom1, kolom2, kolom3, kolom4 = st.columns(4)

kolom1.metric("Jumlah Observasi", f"{len(data):,}")

if "Kota" in data.columns:
    kolom2.metric(
        "Jumlah Kota",
        f"{data['Kota'].nunique():,}"
    )

if "Tahun" in data.columns:
    kolom3.metric(
        "Jumlah Tahun",
        f"{data['Tahun'].nunique():,}"
    )

kolom4.metric(
    "Jumlah Variabel",
    f"{len(data.columns):,}"
)

st.divider()

# =====================================
# 6. TAB DASHBOARD
# =====================================
tab1, tab2, tab3, tab4 = st.tabs([
    "📋 Data",
    "📈 Tren",
    "📊 Statistik",
    "🔗 Korelasi"
])

# -------------------------------------
# TAB 1: DATA
# -------------------------------------
with tab1:
    st.subheader("Tabel Dataset")

    st.dataframe(
        data,
        use_container_width=True,
        hide_index=True
    )

    csv = data.to_csv(index=False).encode("utf-8")

    st.download_button(
        "⬇️ Download Data CSV",
        data=csv,
        file_name="data_fiskal_filtered.csv",
        mime="text/csv"
    )

# -------------------------------------
# TAB 2: TREN
# -------------------------------------
with tab2:
    st.subheader("Tren Indikator Berdasarkan Tahun")

    kolom_numerik = data.select_dtypes(
        include="number"
    ).columns.tolist()

    variabel = [
        c for c in kolom_numerik if c != "Tahun"
    ]

    if variabel:
        indikator = st.selectbox(
            "Pilih Indikator",
            options=variabel
        )

        if "Tahun" in data.columns:
            tren = (
                data.groupby(
                    ["Tahun", "Kota"] if "Kota" in data.columns
                    else ["Tahun"],
                    as_index=False
                )[indikator]
                .mean()
            )

            fig = px.line(
                tren,
                x="Tahun",
                y=indikator,
                color="Kota" if "Kota" in tren.columns else None,
                markers=True,
                title=f"Tren {indikator} per Tahun"
            )

            fig.update_layout(
                xaxis_title="Tahun",
                yaxis_title=indikator,
                legend_title="Kota"
            )

            st.plotly_chart(
                fig,
                use_container_width=True
            )

            st.caption(
                "Nilai merupakan rata-rata per kota dan tahun "
                "jika terdapat lebih dari satu observasi."
            )
        else:
            st.info("Kolom Tahun tidak tersedia.")

# -------------------------------------
# TAB 3: STATISTIK DESKRIPTIF
# -------------------------------------
with tab3:
    st.subheader("Statistik Deskriptif")

    kolom_numerik = data.select_dtypes(
        include="number"
    ).columns.tolist()

    if kolom_numerik:
        statistik = data[kolom_numerik].describe().T

        statistik["median"] = data[
            kolom_numerik
        ].median()

        statistik["missing"] = data[
            kolom_numerik
        ].isna().sum()

        st.dataframe(
            statistik.round(3),
            use_container_width=True
        )

        indikator_stat = st.selectbox(
            "Pilih variabel untuk melihat distribusi",
            options=[
                c for c in kolom_numerik if c != "Tahun"
            ],
            key="distribusi"
        )

        fig_hist = px.histogram(
            data,
            x=indikator_stat,
            nbins=20,
            title=f"Distribusi {indikator_stat}"
        )

        st.plotly_chart(
            fig_hist,
            use_container_width=True
        )

# -------------------------------------
# TAB 4: KORELASI
# -------------------------------------
with tab4:
    st.subheader("Hubungan Antarvariabel")

    kolom_numerik = [
        c for c in data.select_dtypes(
            include="number"
        ).columns
        if c != "Tahun"
    ]

    if len(kolom_numerik) >= 2:
        x_var = st.selectbox(
            "Variabel X",
            kolom_numerik,
            index=0
        )

        y_var = st.selectbox(
            "Variabel Y",
            kolom_numerik,
            index=1
        )

        pasangan = data[[x_var, y_var]].dropna()

        if len(pasangan) >= 2:
            korelasi = pasangan[x_var].corr(
                pasangan[y_var]
            )

            st.metric(
                "Korelasi Pearson",
                f"{korelasi:.3f}"
            )

            fig_scatter = px.scatter(
                data,
                x=x_var,
                y=y_var,
                color="Kota" if "Kota" in data.columns else None,
                hover_data=["Tahun"] if "Tahun" in data.columns else None,
                title=f"{x_var} vs {y_var}",
                trendline="ols" if len(pasangan) >= 2 else None
            )

            st.plotly_chart(
                fig_scatter,
                use_container_width=True
            )

            st.caption(
                "Korelasi menunjukkan hubungan linear, "
                "bukan bukti sebab-akibat."
            )
        else:
            st.warning("Data tidak cukup untuk menghitung korelasi.")

st.divider()
st.caption("Dashboard Data Fiskal Daerah | Sumber: Dataset GitHub DATAAKSI")
